raw=(ROOT/'output/poster/patchcore_poster_talk_en_final.md').read_text(encoding='utf-8')
lines=[]
active=False
for s in raw.splitlines():
    if s.startswith('## '):
        active=True
    elif active and s.strip() and not s.startswith('>'):
        lines.append(s)
assert len(lines)==len(KANA),(len(lines),len(KANA))
fonts()
eng=ParagraphStyle('English',fontName='EN',fontSize=9.5,leading=10.5,spaceAfter=1)
kana=ParagraphStyle('Kana',fontName='JA',fontSize=7,leading=8.5,wordWrap='CJK',textColor=colors.HexColor('#333333'))
story=[]
md=[]
for line,reading in zip(lines,KANA):
    text=re.sub(r'\*\*(.*?)\*\*',r'<b>\1</b>',escape(line))
    story.append(KeepTogether([Paragraph(text,eng),Paragraph(escape(reading),kana)]))
    md.extend([line,reading,''])
(ROOT/'output/poster/patchcore_poster_talk_kana.md').write_text('\n\n'.join(md),encoding='utf-8')
out=ROOT/'output/pdf/patchcore_poster_talk_kana.pdf'
def footer(c,d):
    c.setFont('EN',9)
    c.drawRightString(A4[0]-40,22,str(d.page))
SimpleDocTemplate(str(out),pagesize=A4,leftMargin=30,rightMargin=30,topMargin=25,bottomMargin=30,
                  title='Poster Talk - Kana Practice',author='Shunya Yamada').build(story,onFirstPage=footer,onLaterPages=footer)
reader=PdfReader(out)
print('Sentence pairs:',len(lines),'Pages:',len(reader.pages),out)
tmp=ROOT/'tmp/pdfs/talk'
doc=pdfium.PdfDocument(str(out))
for n,page in enumerate(doc):
    page.render(scale=1.1).to_pil().save(tmp/f'kana_{n+1}.png')
